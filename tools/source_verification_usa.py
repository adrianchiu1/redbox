def _esa_identity(fam) -> float:
    total = None
    for code, meta in config.tree_lines("ESA_EXP").items():
        if config.is_total(meta):
            continue
        plus, minus = fam.esa_exp_parts(ISO3, meta)
        s = sum(plus[1:], plus[0]) - sum(minus, pd.Series(0.0, index=plus[0].index))
        total = s if total is None else total + s
    return float((total - fam.totals(ISO3)["TE"]).abs().max())


def _rev_identity(fam, otr) -> float:
    total = sum((s for s, _, _ in fam.revenue_lines(ISO3).values()), pd.Series(0.0, index=otr.index))
    return float((total - otr).abs().max())


