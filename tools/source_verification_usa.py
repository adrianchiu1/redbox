ISO3 = "USA"


def _mn(x: float) -> str:
    return f"{x:,.0f}"


def _harvest_record() -> list[dict]:
    """The latest usable snapshot per USA-relevant (source, part)."""
    keep = ("OECD_T12_EXP", "OECD_T12_REV", "OECD_T12_BAL", "OECD_T10", "OECD_T1", "OECD_EO",
            "OECD_T11", "OECD_RS", "IMF_GFS", "BEA_NIPA", "FRB_Z1", "OMB_BUDGET", "CBO_BASELINE",
            "CMS_TRUSTEES", "EC_AMECO")
    rows = []
    for (sid, part), e in sorted(R.latest_snapshots().items()):
        if sid in keep and (part in ("", "annual", "quarterly", "register", "current",
                                     "expanded_tables_2026", "baselines", "actuals")
                            or "USA" in part or sid in ("OMB_BUDGET", "EC_AMECO")):
            rows.append({"source_id": sid, "part": part, "retrieved": e["retrieved_at"],
                         "sha256": e["sha256"][:12], "bytes": e.get("size", "")})
        if sid.startswith("IMF_WEO_") and part.startswith("USA_"):
            rows.append({"source_id": sid, "part": part, "retrieved": e["retrieved_at"],
                         "sha256": e["sha256"][:12], "bytes": e.get("size", "")})
    return rows


